"""Слепой контроль: дефект в кейс подкладывает не автор — и, может быть, никто.

Правило остановки требует, чтобы объявленные до контакта контроли сработали.
Четырнадцать кейсов эти контроли выбирал автор, и отсюда дыра, названная в
тексте самого правила: их срабатывание доказывает, что инструмент видит то, что
автор УМЕЕТ подложить, и молчит обо всём, чего автор подложить не догадался.

ЧТО ЗДЕСЬ ОБЕСПЕЧЕНО, А ЧТО НЕТ. Слепота автора НЕ обеспечивается устройством и
обеспечена быть не может: файл лежит на диске, и у автора есть доступ к диску.
Обеспечено другое — невозможность переписать ответ ЗАДНИМ ЧИСЛОМ, когда
результаты известны: отпечаток вписан в пре-регистрацию до прогона.

Была версия, где программу запускал человек, и утверждалось, будто от этого
слепота становится свойством устройства. Утверждение ложно: ответ не попадает в
контекст автора в любом случае — печатается только отпечаток, — а прочитать
файл автор может одинаково независимо от того, кто набрал команду. Ручной шаг
не давал ничего, кроме круга через человека на каждом отказе, и был подстройкой
под запрет среды, выданной за достоинство.

Слепота держится стенограммой сессии: всякое чтение запечатанного файла в ней
видно. Это ревизуемость, а не невозможность, и называть её иначе нельзя.

Устройство. Вторая сторона получает построитель кейса, формуляр и каталог того,
что ядро берётся находить; выбирает сама; выдаёт правку патчем в поток. Поток
перехватывается программой, патч применяется не читая, автору достаётся только
отпечаток. Права записи второй стороне не выдаются: весь её результат
помещается в поток вывода.

ДВЕ СТУПЕНИ РАСКРЫТИЯ. Пятнадцатый кейс показал, что одного запечатанного
файла мало: молчание ядра означало сразу два события — «контроль был пуст» и
«дефект подложен и не увиден», — и различить их было нечем. Поэтому ответ
раскрывается порознь и под разными отпечатками:

1. `--verify-empty` — БЫЛ ЛИ контроль пустым. Этого достаточно, чтобы прочесть
   исход, и недостаточно, чтобы узнать дефект;
2. `--verify` — сам дефект, для разбора после.

Бит пустоты пишет сама программа, а не вторая сторона: она делает бросок и
знает ответ достовернее.

ПУСТОЙ КОНТРОЛЬ. С вероятностью, объявленной в `EMPTY_RATE`, второй стороне
велено НЕ подкладывать ничего. Без этого молчание ядра имело бы единственное
прочтение — «ядро слепо», — и испытание мерило бы только чувствительность,
ничего не говоря о ложных тревогах. Автор знает частоту пустых прогонов и не
знает исхода броска: бросок происходит здесь и попадает только в запечатанный
файл.

ОДИН ДЕФЕКТ, А НЕ ДВА. Два дефекта взаимодействуют, и после раскрытия начинается
спор о том, какой именно сигнал сработал. По той же причине запечатанный файл
обязан назвать ожидаемую находку ПО ИМЕНИ: соответствие проверяется объявленным
заранее правилом, а не толкованием.

Что испытание доказывает: инструмент прошёл проспективное слепое испытание на
независимо выбранном синтетическом дефекте из объявленного пространства находок.
Чего НЕ доказывает: что инструмент видит дефекты вне этого пространства; что
синтетический дефект похож на настоящий; что вторая сторона не разделяет слепых
пятен автора — она языковая модель и каталог получает от автора.
"""

from __future__ import annotations

import argparse
import hashlib
import re
import secrets
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
"""Корень проекта. Пути от него, а не от текущего каталога: инструмент,
работающий только из корня, — уже записанный класс журнала повторов."""

SEALED = "blind-control.sealed.md"
EMPTY_BIT = "blind-control.empty.md"
PATCH = "blind-control.patch"

EMPTY_RATE = 3
"""Один прогон из этого числа — пустой: подкладывать нечего.

Частота объявлена, исход броска — нет. Знание частоты не помогает: оно
позволяет рассуждать о вероятностях после прогона и не говорит ничего до него.
"""

COMMON = """Ты вторая сторона в слепом контроле над инструментом анализа данных.

Автор инструмента узнает твой ответ только ПОСЛЕ прогона. Поэтому НЕ пиши о
своём выборе ничего, кроме как внутри требуемого ниже патча: ни в терминал, ни
в другие файлы.

Прочитай {findings} — каталог того, что ядро берётся находить. Прочитай также
{build} и {form}.

Ответ выдай ОДНИМ unified diff и больше ничем. Первая строка ответа обязана
начинаться с `diff --git`. Патч обязан создавать новый файл {sealed}.
"""

PLANT = """
Твоя работа: выбрать ОДИН пункт каталога и внести соответствующий дефект.
Выбирай то, что автор, по-твоему, подкладывать бы не стал.

Правила:
1. Правь только {build} и {form}. Ничего в src/ не трогай.
2. Дефект вносится в ПОСТРОЕНИЕ ДАННЫХ или в ОБЪЯВЛЕНИЯ — так, как его внёс бы
   невнимательный аналитик. Синтаксис не ломай: `python {build}` обязан
   отработать и напечатать число строк.
3. Дефект обязан соответствовать выбранному пункту каталога: ядро должно ИМЕТЬ
   ПРАВО его заметить.
4. Один дефект, не два. Два взаимодействуют, и после раскрытия неясно, какой
   именно сигнал сработал.
5. Не оставляй комментариев, называющих подлог.

В {sealed} напиши по-русски:
- ОЖИДАЕМАЯ НАХОДКА: точное имя пункта каталога, одной строкой;
- какой пункт выбран и почему именно он;
- что именно изменено, построчно;
- если ждёшь, что ядро промолчит, — почему.
"""

EXCLUDED = """
Эти пункты каталога уже испытаны в прежних кейсах, и выбирать их НЕЛЬЗЯ:
{tried}

Повторный выбор ничего нового об инструменте не скажет: под этим самым
протоколом он такой дефект уже находил.
"""
"""Дописывается к заданию, когда испытанные пункты есть.

Появился после того, как вторая сторона два кейса подряд выбрала
`duplicate_rows`. Третий такой выбор сделал бы испытание неотличимым от
авторского контроля на том же дефекте.

Плата названа в docs/blind-controls.md: список составляет автор, и сужение
пространства — ещё один способ, которым авторский выбор просачивается в
испытание независимости выбора.
"""

EMPTY = """
Твоя работа в этот раз — НЕ ВНОСИТЬ НИКАКОГО ДЕФЕКТА. Это пустой контроль:
он проверяет, не поднимает ли ядро тревогу на ровном месте.

{build} и {form} не меняй ни единым символом. Патч обязан создавать ровно один
файл — {sealed} — и ничего больше.

В {sealed} напиши по-русски:
- ОЖИДАЕМАЯ НАХОДКА: нет, это пустой контроль;
- какой дефект ты бы выбрал, если бы подкладывал, и почему именно его.
"""


HEADER = re.compile(
    r"^(diff |index |old mode |new mode |new file mode |deleted file mode |"
    r"similarity index |dissimilarity index |rename from |rename to |copy from |"
    r"copy to |--- |\+\+\+ |@@ |Binary files )"
)
BODY = re.compile(r"^[ +\-\\]")


def _extract_patch(raw: str) -> str:
    """Вырезать патч из вывода второй стороны — программой, а не глазами.

    Прочитав вывод, человек увидел бы подлог, и контроль перестал бы быть
    слепым для него тоже.

    Первая версия знала три начала строки и обрывала патч на всём остальном.
    Настоящий патч, создающий файл, второй строкой несёт `new file mode
    100644`, — и вырезалась ровно одна строка заголовка, 111 байт, после чего
    `git apply` отказывал. Ни один тест этого не поймал: все проверяли патч,
    правящий существующий файл.

    Пустая строка тоже тело патча: это контекстная строка пустой строки файла.
    Прежнее правило требовало хотя бы одного символа и обрывалось на ней.
    """
    start = raw.find("diff --git")
    if start == -1:
        return ""
    lines: list[str] = []
    for line in raw[start:].splitlines():
        if not line or HEADER.match(line) or BODY.match(line):
            lines.append(line)
            continue
        break
    while lines and not lines[-1]:
        lines.pop()
    return "\n".join(lines) + "\n"


def _apply(patch_path: Path) -> bool:
    """Применить патч, перепробовав обычные различия в его оформлении.

    Вторая сторона пишет патч руками, и счётчики строк в заголовках кусков у
    неё сбиваются, а префиксы путей бывают и `a/b/`, и без них. Спорить об этом
    после отказа нельзя: чтобы поправить патч, его пришлось бы прочитать.
    """
    for extra in ([], ["-p0"], ["--3way"]):
        done = subprocess.run(
            ["git", "apply", "--recount", *extra, str(patch_path)],
            capture_output=True,
            text=True,
        )
        if done.returncode == 0:
            return True
    return False


def _findings_catalogue() -> Path | None:
    """Файл, где объявлен перечень находок ядра.

    Ищется ПО СОДЕРЖИМОМУ, а не по имени. Первая версия искала `finding*.py` —
    догадку о названии файла, которую ни разу не запустили; перечень лежит в
    `evals/case.py`, и при первом же настоящем запуске инструмент отказал, не
    успев ничего сделать. Имя файла может смениться, объявление класса — нет.
    """
    for path in sorted((ROOT / "src/dsx").rglob("*.py")):
        if "class Finding(" in path.read_text(encoding="utf-8"):
            return path
    return None


def _finding_names(catalogue: Path) -> frozenset[str]:
    """Имена пунктов каталога — из объявления перечисления, не из догадки.

    Читается текстом, а не импортом: инструмент запускают системным python, и
    установка пакета ему не обещана.

    Берётся ровно тело `class Finding`. Первая версия читала файл целиком и
    прихватывала соседний перечень вердиктов — `pass`, `missed`, `both`; они
    пунктами каталога не являются и исключать их из выбора было бы неправдой.
    """
    text = catalogue.read_text(encoding="utf-8")
    start = text.index("class Finding(")
    tail = re.search(r"^class ", text[start + 1 :], re.MULTILINE)
    body = text[start : start + 1 + tail.start()] if tail else text[start:]
    return frozenset(re.findall(r'^\s+[A-Z_]+ = "([a-z_]+)"$', body, re.MULTILINE))


EXPECTED = re.compile(r"^ОЖИДАЕМАЯ НАХОДКА:(.*)$", re.MULTILINE)


def _already_tried(project: Path, names: frozenset[str]) -> tuple[list[str], list[str]]:
    """Пункты каталога, испытанные в прежних кейсах, и жалобы на неразобранное.

    Список собирается ИЗ ЗАПЕЧАТАННЫХ ФАЙЛОВ, а не из ведомости, которую автор
    заполняет руками. Две меры проекта — учёт ошибок автора и учёт правила
    остановки — были объявлены действующими и не заполнялись; ведомость здесь
    повторила бы это в третий раз.

    Пустой контроль пункта не тратит: подкладывать было нечего, и строка
    ожидаемой находки в нём не называет имени каталога.
    """
    tried: set[str] = set()
    complaints: list[str] = []
    here = project.resolve()
    for sealed in sorted((ROOT / "projects").glob(f"*/{SEALED}")):
        if sealed.parent.resolve() == here:
            continue
        for line in EXPECTED.findall(sealed.read_text(encoding="utf-8")):
            found = {word for word in re.findall(r"[a-z_]{4,}", line) if word in names}
            if found:
                tried |= found
            elif "пуст" not in line:
                complaints.append(f"{sealed}: имя находки не разобрано — {line.strip()!r}")
    return sorted(tried), complaints


TECHNICAL = (
    ("usage limit", "лимит второй стороны исчерпан — контроль не состоялся"),
    ("stdin", "вторая сторона ждала ввода: запуск с открытым stdin"),
    ("not found", "второй стороны нет на рабочем пути"),
    ("authenticat", "вторая сторона не авторизована"),
    ("rate limit", "вторая сторона ограничила частоту запросов"),
)
"""Технические причины отказа, которые можно назвать вслух.

Причина отказа НЕ печаталась вовсе: в жалобах инструмента мог оказаться текст
патча, а прочитав его, автор перестал бы быть слепым. Плата за молчание
обнаружилась в девятнадцатом кейсе — исчерпанный лимит и повисший на вводе
процесс выглядели одинаково, и час ушёл на то, чтобы их различить.

Список узкий намеренно: печатается ЗАРАНЕЕ НАПИСАННАЯ фраза, а не строка из
вывода второй стороны. Совпадение ищется по слову, которое не может быть частью
патча к построителю кейса.
"""


def _technical_cause(*streams: str) -> str:
    """Назвать техническую причину отказа, не показывая вывода."""
    haystack = " ".join(streams).lower()
    for token, said in TECHNICAL:
        if token in haystack:
            return f"  причина: {said}"
    return "  причина не распознана; читать поток нельзя — в нём мог быть патч"


def _plant(project: Path) -> int:
    sealed = project / SEALED
    if sealed.exists():
        print(f"ОТКАЗ: {sealed} уже существует.")
        print("Слепой контроль не переигрывают: перезапуск после увиденных")
        print("результатов возвращает выбор автору, ради отнятия которого всё и сделано.")
        return 1

    findings = _findings_catalogue()
    if findings is None:
        print("ОТКАЗ: каталог находок не найден — второй стороне не из чего выбирать")
        return 1

    parts = {
        "findings": findings,
        "build": project / "build.py",
        "form": project / "project.yaml",
        "sealed": sealed,
    }
    tried, complaints = _already_tried(project, _finding_names(findings))
    for complaint in complaints:
        print(f"ВНИМАНИЕ: {complaint}")
    if tried:
        print("Уже испытано и потому исключено из выбора: " + ", ".join(tried))
    else:
        print("Исключать нечего: под этим протоколом ещё не испытан ни один пункт каталога.")

    # Бросок происходит ЗДЕСЬ и попадает только в запечатанный файл.
    empty = secrets.randbelow(EMPTY_RATE) == 0
    task = COMMON.format(**parts) + (EMPTY if empty else PLANT).format(**parts)
    if tried and not empty:
        task += EXCLUDED.format(tried="\n".join(f"- {name}" for name in tried))

    result = subprocess.run(
        ["codex", "exec", "--skip-git-repo-check", task],
        capture_output=True,
        text=True,
        # Закрытый ввод обязателен. Codex CLI 0.153 при живом stdin печатает
        # «Reading additional input from stdin...» и ждёт — в фоне это висит,
        # пока кто-нибудь не убьёт процесс. Задание передано аргументом, читать
        # ему нечего, и молчаливое ожидание выглядело отказом инструмента.
        stdin=subprocess.DEVNULL,
    )
    if result.returncode != 0:
        print(f"ОТКАЗ: вторая сторона завершилась с кодом {result.returncode}")
        print(_technical_cause(result.stderr, result.stdout))
        return 1

    patch = _extract_patch(result.stdout)
    if not patch:
        print("ОТКАЗ: вторая сторона не выдала патча — контроля не было")
        return 1

    patch_path = project / PATCH
    patch_path.write_text(patch, encoding="utf-8")
    if not _apply(patch_path):
        # Причину не печатаем: в отказе git цитирует строки патча.
        print(f"ОТКАЗ: патч не применился. Он лежит в {patch_path};")
        print("читать его нельзя — контроль тогда перестанет быть слепым.")
        return 1

    if not sealed.exists():
        print(f"ОТКАЗ: патч применился, но {SEALED} не создан — ответа нет")
        return 1

    # Бит пустоты — отдельный файл под отдельным отпечатком. Раскрывается
    # первым и говорит ровно одно: было ли что подкладывать.
    bit = project / EMPTY_BIT
    bit.write_text(
        f"Контроль был {'ПУСТЫМ' if empty else 'НЕПУСТЫМ'}.\n\nСоль: {secrets.token_hex(16)}\n",
        encoding="utf-8",
    )

    # Соль дописывается ПОСЛЕ применения и делает отпечаток неперебираемым даже
    # для короткого ответа. Живёт она в самом запечатанном файле: прятать её
    # отдельно значило бы завести второй секрет там, где хватает одного.
    with sealed.open("a", encoding="utf-8") as handle:
        handle.write(f"\n\nСоль: {secrets.token_hex(16)}\n")

    digest = hashlib.sha256(sealed.read_bytes()).hexdigest()[:12]
    bit_digest = hashlib.sha256(bit.read_bytes()).hexdigest()[:12]
    name = Path(__file__).name
    print("Слепой контроль внесён. Впишите ОБА отпечатка в пре-регистрацию до прогона.")
    print(f"  бит пустоты: {bit_digest}")
    print(f"  ответ:       {digest}")
    print(f"Ни {EMPTY_BIT}, ни {SEALED}, ни {PATCH} до записи заключения не читать.")
    print(f"После записи заключения: python {name} {project} --verify-empty {bit_digest}")
    print(f"Затем, для разбора:      python {name} {project} --verify {digest}")
    return 0


def _verify(project: Path, expected: str, filename: str = SEALED) -> int:
    sealed = project / filename
    if not sealed.exists():
        print(f"ОТКАЗ: {sealed} не найден — раскрывать нечего")
        return 1
    digest = hashlib.sha256(sealed.read_bytes()).hexdigest()[:12]
    if digest != expected:
        print(f"ОТКАЗ: отпечаток не сошёлся. Ожидался {expected}, получен {digest}.")
        print("Файл изменён после запечатывания, и ответу верить нельзя.")
        return 1
    print(f"Отпечаток сошёлся: {digest}. Ответ второй стороны:\n")
    print(sealed.read_text(encoding="utf-8"))
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description="слепой контроль над кейсом")
    parser.add_argument("project", type=Path, help="каталог проекта")
    parser.add_argument(
        "--verify-empty",
        metavar="ОТПЕЧАТОК",
        help="раскрыть ПЕРВУЮ ступень: был ли контроль пустым",
    )
    parser.add_argument("--verify", metavar="ОТПЕЧАТОК", help="раскрыть сам дефект, для разбора")
    args = parser.parse_args()

    if args.verify_empty:
        return _verify(args.project, args.verify_empty, EMPTY_BIT)
    if args.verify:
        return _verify(args.project, args.verify)
    return _plant(args.project)


