"""Слепой контроль: дефект в кейс подкладывает не автор — и, может быть, никто.

Правило остановки требует, чтобы объявленные до контакта контроли сработали.
Четырнадцать кейсов эти контроли выбирал автор, и отсюда дыра, названная в
тексте самого правила: их срабатывание доказывает, что инструмент видит то, что
автор УМЕЕТ подложить, и молчит обо всём, чего автор подложить не догадался.

ЗАПУСКАЕТ ЭТУ ПРОГРАММУ ВЛАДЕЛЕЦ ПРОЕКТА, А НЕ АВТОР. Это не формальность.
Отпечаток мешает переписать ответ задним числом, но не мешает автору заглянуть
в файл раньше времени: файл лежит на диске. Когда программу запускает человек,
запечатанный ответ вообще не попадает в контекст автора, и слепота перестаёт
быть обещанием, становясь свойством устройства.

Устройство. Вторая сторона получает построитель кейса, формуляр и каталог того,
что ядро берётся находить; выбирает сама; выдаёт правку патчем в поток. Поток
перехватывается программой, патч применяется не читая, автору достаётся только
отпечаток. Права записи второй стороне не выдаются: весь её результат
помещается в поток вывода.

ПУСТОЙ КОНТРОЛЬ. С вероятностью, объявленной в `EMPTY_RATE`, второй стороне
велено НЕ подкладывать ничего. Без этого молчание ядра имело бы единственное
прочтение — «ядро слепо», — и испытание мерило бы только чувствительность,
ничего не говоря о ложных тревогах. Автор знает частоту пустых прогонов и не
знает исхода броска: бросок происходит здесь и попадает только в запечатанный
файл.

ОДИН ДЕФЕКТ, А НЕ ДВА. Два дефекта взаимодействуют, и после раскрытия начинается
спор о том, какой именно сигнал сработал. По той же причине запечатанный файл
обязан назвать ожидаемую находку ПО ИМЕНИ: соответствие проверяется объявленным
заранее правилом, а не толкованием.

Что испытание доказывает: инструмент прошёл проспективное слепое испытание на
независимо выбранном синтетическом дефекте из объявленного пространства находок.
Чего НЕ доказывает: что инструмент видит дефекты вне этого пространства; что
синтетический дефект похож на настоящий; что вторая сторона не разделяет слепых
пятен автора — она языковая модель и каталог получает от автора.
"""

from __future__ import annotations

import argparse
import hashlib
import re
import secrets
import subprocess
import sys
from pathlib import Path

SEALED = "blind-control.sealed.md"
PATCH = "blind-control.patch"

EMPTY_RATE = 3
"""Один прогон из этого числа — пустой: подкладывать нечего.

Частота объявлена, исход броска — нет. Знание частоты не помогает: оно
позволяет рассуждать о вероятностях после прогона и не говорит ничего до него.
"""

COMMON = """Ты вторая сторона в слепом контроле над инструментом анализа данных.

Автор инструмента узнает твой ответ только ПОСЛЕ прогона. Поэтому НЕ пиши о
своём выборе ничего, кроме как внутри требуемого ниже патча: ни в терминал, ни
в другие файлы.

Прочитай {findings} — каталог того, что ядро берётся находить. Прочитай также
{build} и {form}.

Ответ выдай ОДНИМ unified diff и больше ничем. Первая строка ответа обязана
начинаться с `diff --git`. Патч обязан создавать новый файл {sealed}.
"""

PLANT = """
Твоя работа: выбрать ОДИН пункт каталога и внести соответствующий дефект.
Выбирай то, что автор, по-твоему, подкладывать бы не стал.

Правила:
1. Правь только {build} и {form}. Ничего в src/ не трогай.
2. Дефект вносится в ПОСТРОЕНИЕ ДАННЫХ или в ОБЪЯВЛЕНИЯ — так, как его внёс бы
   невнимательный аналитик. Синтаксис не ломай: `python {build}` обязан
   отработать и напечатать число строк.
3. Дефект обязан соответствовать выбранному пункту каталога: ядро должно ИМЕТЬ
   ПРАВО его заметить.
4. Один дефект, не два. Два взаимодействуют, и после раскрытия неясно, какой
   именно сигнал сработал.
5. Не оставляй комментариев, называющих подлог.

В {sealed} напиши по-русски:
- ОЖИДАЕМАЯ НАХОДКА: точное имя пункта каталога, одной строкой;
- какой пункт выбран и почему именно он;
- что именно изменено, построчно;
- если ждёшь, что ядро промолчит, — почему.
"""

EMPTY = """
Твоя работа в этот раз — НЕ ВНОСИТЬ НИКАКОГО ДЕФЕКТА. Это пустой контроль:
он проверяет, не поднимает ли ядро тревогу на ровном месте.

{build} и {form} не меняй ни единым символом. Патч обязан создавать ровно один
файл — {sealed} — и ничего больше.

В {sealed} напиши по-русски:
- ОЖИДАЕМАЯ НАХОДКА: нет, это пустой контроль;
- какой дефект ты бы выбрал, если бы подкладывал, и почему именно его.
"""


HEADER = re.compile(
    r"^(diff |index |old mode |new mode |new file mode |deleted file mode |"
    r"similarity index |dissimilarity index |rename from |rename to |copy from |"
    r"copy to |--- |\+\+\+ |@@ |Binary files )"
)
BODY = re.compile(r"^[ +\-\\]")


def _extract_patch(raw: str) -> str:
    """Вырезать патч из вывода второй стороны — программой, а не глазами.

    Прочитав вывод, человек увидел бы подлог, и контроль перестал бы быть
    слепым для него тоже.

    Первая версия знала три начала строки и обрывала патч на всём остальном.
    Настоящий патч, создающий файл, второй строкой несёт `new file mode
    100644`, — и вырезалась ровно одна строка заголовка, 111 байт, после чего
    `git apply` отказывал. Ни один тест этого не поймал: все проверяли патч,
    правящий существующий файл.

    Пустая строка тоже тело патча: это контекстная строка пустой строки файла.
    Прежнее правило требовало хотя бы одного символа и обрывалось на ней.
    """
    start = raw.find("diff --git")
    if start == -1:
        return ""
    lines: list[str] = []
    for line in raw[start:].splitlines():
        if not line or HEADER.match(line) or BODY.match(line):
            lines.append(line)
            continue
        break
    while lines and not lines[-1]:
        lines.pop()
    return "\n".join(lines) + "\n"


def _apply(patch_path: Path) -> bool:
    """Применить патч, перепробовав обычные различия в его оформлении.

    Вторая сторона пишет патч руками, и счётчики строк в заголовках кусков у
    неё сбиваются, а префиксы путей бывают и `a/b/`, и без них. Спорить об этом
    после отказа нельзя: чтобы поправить патч, его пришлось бы прочитать.
    """
    for extra in ([], ["-p0"], ["--3way"]):
        done = subprocess.run(
            ["git", "apply", "--recount", *extra, str(patch_path)],
            capture_output=True,
            text=True,
        )
        if done.returncode == 0:
            return True
    return False


def _findings_catalogue() -> Path | None:
    """Файл, где объявлен перечень находок ядра.

    Ищется ПО СОДЕРЖИМОМУ, а не по имени. Первая версия искала `finding*.py` —
    догадку о названии файла, которую ни разу не запустили; перечень лежит в
    `evals/case.py`, и при первом же настоящем запуске инструмент отказал, не
    успев ничего сделать. Имя файла может смениться, объявление класса — нет.
    """
    for path in sorted(Path("src/dsx").rglob("*.py")):
        if "class Finding(" in path.read_text(encoding="utf-8"):
            return path
    return None


def _plant(project: Path) -> int:
    sealed = project / SEALED
    if sealed.exists():
        print(f"ОТКАЗ: {sealed} уже существует.")
        print("Слепой контроль не переигрывают: перезапуск после увиденных")
        print("результатов возвращает выбор автору, ради отнятия которого всё и сделано.")
        return 1

    findings = _findings_catalogue()
    if findings is None:
        print("ОТКАЗ: каталог находок не найден — второй стороне не из чего выбирать")
        return 1

    parts = {
        "findings": findings,
        "build": project / "build.py",
        "form": project / "project.yaml",
        "sealed": sealed,
    }
    # Бросок происходит ЗДЕСЬ и попадает только в запечатанный файл.
    empty = secrets.randbelow(EMPTY_RATE) == 0
    task = COMMON.format(**parts) + (EMPTY if empty else PLANT).format(**parts)

    result = subprocess.run(
        ["codex", "exec", "--skip-git-repo-check", task],
        capture_output=True,
        text=True,
    )
    if result.returncode != 0:
        print(f"ОТКАЗ: вторая сторона завершилась с кодом {result.returncode}")
        return 1

    patch = _extract_patch(result.stdout)
    if not patch:
        print("ОТКАЗ: вторая сторона не выдала патча — контроля не было")
        return 1

    patch_path = project / PATCH
    patch_path.write_text(patch, encoding="utf-8")
    if not _apply(patch_path):
        # Причину не печатаем: в отказе git цитирует строки патча.
        print(f"ОТКАЗ: патч не применился. Он лежит в {patch_path};")
        print("читать его нельзя — контроль тогда перестанет быть слепым.")
        return 1

    if not sealed.exists():
        print(f"ОТКАЗ: патч применился, но {SEALED} не создан — ответа нет")
        return 1

    # Соль дописывается ПОСЛЕ применения и делает отпечаток неперебираемым даже
    # для короткого ответа. Живёт она в самом запечатанном файле: прятать её
    # отдельно значило бы завести второй секрет там, где хватает одного.
    with sealed.open("a", encoding="utf-8") as handle:
        handle.write(f"\n\nСоль: {secrets.token_hex(16)}\n")

    digest = hashlib.sha256(sealed.read_bytes()).hexdigest()[:12]
    print("Слепой контроль внесён. Что делать дальше:")
    print(f"  1. Передайте автору отпечаток: {digest}")
    print("  2. Он впишет его в пре-регистрацию и проведёт прогон.")
    print(f"  3. НЕ показывайте ему {sealed} и {patch_path} до конца прогона.")
    print(f"  4. После прогона: python {Path(__file__).name} {project} --verify {digest}")
    return 0


def _verify(project: Path, expected: str) -> int:
    sealed = project / SEALED
    if not sealed.exists():
        print(f"ОТКАЗ: {sealed} не найден — раскрывать нечего")
        return 1
    digest = hashlib.sha256(sealed.read_bytes()).hexdigest()[:12]
    if digest != expected:
        print(f"ОТКАЗ: отпечаток не сошёлся. Ожидался {expected}, получен {digest}.")
        print("Файл изменён после запечатывания, и ответу верить нельзя.")
        return 1
    print(f"Отпечаток сошёлся: {digest}. Ответ второй стороны:\n")
    print(sealed.read_text(encoding="utf-8"))
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description="слепой контроль над кейсом")
    parser.add_argument("project", type=Path, help="каталог проекта")
    parser.add_argument("--verify", metavar="ОТПЕЧАТОК", help="раскрыть ответ после прогона")
    args = parser.parse_args()

    if args.verify:
        return _verify(args.project, args.verify)
    return _plant(args.project)


if __name__ == "__main__":
    sys.exit(main())
