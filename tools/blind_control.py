"""Слепой контроль: дефект в кейс подкладывает не автор.

Правило остановки требует, чтобы объявленные до контакта контроли сработали.
Четырнадцать кейсов эти контроли выбирал автор, и у правила отсюда дыра,
названная в его же тексте: сработавшие контроли доказывают, что инструмент
видит то, что автор УМЕЕТ подложить, и молчат о том, чего автор подложить не
догадался.

Здесь выбор у автора отбирается. Вторая сторона получает построитель кейса,
формуляр и перечень того, что ядро берётся находить; выбирает сама; выдаёт
правку патчем в поток. Поток перенаправляется в файл, файл применяется не
читая, и автору достаётся только отпечаток запечатанного ответа.

Почему именно патчем. Вторая сторона запускается в режиме только для чтения:
права записи ей не выдаются, и просить их было бы неоправданно — весь её
результат помещается в поток вывода.

Чего отпечаток НЕ гарантирует: он не мешает автору прочитать ответ раньше
времени. Он мешает другому — переписать ответ ПОСЛЕ того, как результаты
известны. Первое не обеспечивается ничем, кроме стенограммы сессии, и это
записано здесь прямо, а не выдано за гарантию.
"""

from __future__ import annotations

import argparse
import hashlib
import re
import subprocess
import sys
from pathlib import Path

SEALED = "blind-control.sealed.md"

TASK = """Ты вторая сторона в слепом контроле над инструментом анализа данных.

Твоя работа: выбрать дефект, оформить его правкой и записать, что ты сделал.
Автор инструмента твой выбор узнает только ПОСЛЕ прогона, поэтому НЕ пиши о
выборе ничего, кроме как внутри требуемого ниже патча.

Каталог того, что ядро берётся находить, — в файле {findings}. Прочитай его.
Прочитай также {build} и {form}. Выбери ОДИН или ДВА пункта каталога. Выбирай
то, что автор, по-твоему, подкладывать бы не стал.

Правила:
1. Правь только {build} и {form}. Ничего в src/ не трогай.
2. Дефект вносится в ПОСТРОЕНИЕ ДАННЫХ или в ОБЪЯВЛЕНИЯ — так, как его внёс бы
   невнимательный аналитик. Синтаксис не ломай: `python {build}` обязан
   отработать и напечатать число строк.
3. Ядро должно ИМЕТЬ ПРАВО заметить дефект: он обязан соответствовать выбранным
   пунктам каталога.
4. Не оставляй в коде комментариев, называющих подлог. Правка должна выглядеть
   как обычная строчка работы.

Ответ выдай ОДНИМ unified diff и больше ничем. Ни приветствия, ни пояснений
вокруг: первая строка ответа обязана начинаться с `diff --git`. Пути в патче —
от корня репозитория, без префиксов a/ и b/ менять не нужно, оставь как обычно.

Патч обязан, помимо правки, создавать новый файл {sealed} со следующим
содержанием по-русски:
- какие пункты каталога выбраны и почему именно они;
- что именно изменено, построчно;
- какой сигнал ожидается от ядра;
- если ожидается, что ядро промолчит, — почему."""


def _extract_patch(raw: str) -> str:
    """Вырезать патч из вывода второй стороны.

    Делает это программа, а не автор: прочитав вывод глазами, автор увидел бы
    подлог и контроль перестал бы быть слепым.
    """
    start = raw.find("diff --git")
    if start == -1:
        return ""
    body = raw[start:]
    # Вторая сторона дописывает в конце счётчик токенов. Патч заканчивается
    # там, где начинается строка, не относящаяся к формату diff.
    lines: list[str] = []
    for line in body.splitlines():
        if lines and not re.match(r"^(diff |index |--- |\+\+\+ |@@ |[ +\-\\])", line):
            break
        lines.append(line)
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description="слепой контроль над кейсом")
    parser.add_argument("project", type=Path, help="каталог проекта")
    args = parser.parse_args()

    project: Path = args.project
    sealed = project / SEALED
    if sealed.exists():
        print(f"ОТКАЗ: {sealed} уже существует. Слепой контроль не переигрывают:")
        print("перезапуск после увиденных результатов — это выбор автора обратно.")
        return 1

    findings = next(Path("src/dsx").rglob("finding*.py"), None)
    if findings is None:
        print("ОТКАЗ: каталог находок не найден — второй стороне не из чего выбирать")
        return 1

    task = TASK.format(
        findings=findings,
        build=project / "build.py",
        form=project / "project.yaml",
        sealed=sealed,
    )
    result = subprocess.run(
        ["codex", "exec", "--skip-git-repo-check", task],
        capture_output=True,
        text=True,
    )
    if result.returncode != 0:
        print(f"ОТКАЗ: вторая сторона завершилась с кодом {result.returncode}")
        return 1

    patch = _extract_patch(result.stdout)
    if not patch:
        print("ОТКАЗ: вторая сторона не выдала патча — контроля не было")
        return 1

    patch_path = project / "blind-control.patch"
    patch_path.write_text(patch, encoding="utf-8")
    applied = subprocess.run(
        ["git", "apply", "--verbose", str(patch_path)], capture_output=True, text=True
    )
    if applied.returncode != 0:
        # Причину печатаем, содержимое патча — нет: в отказе git цитирует строки.
        print("ОТКАЗ: патч не применился. Содержимое не показано, чтобы контроль")
        print(f"остался слепым. Патч лежит в {patch_path}, применять его глазами нельзя.")
        return 1

    if not sealed.exists():
        print(f"ОТКАЗ: патч применился, но {SEALED} не создан — ответа нет")
        return 1

    digest = hashlib.sha256(sealed.read_bytes()).hexdigest()[:12]
    print(f"Слепой контроль внесён. Отпечаток запечатанного ответа: {digest}")
    print("Впиши отпечаток в пре-регистрацию. Файл не читай до конца прогона.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
