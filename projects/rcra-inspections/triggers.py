"""Разбиение поводов проверки на вызванные сигналом и плановые.

ОБЪЯВЛЕНО ДО ВЫЧИСЛЕНИЯ ЛЮБОЙ ДОЛИ ИСХОДА, как требует пре-регистрация §3.
Основание каждого отнесения — официальное название кода, а не наблюдаемая
частота нарушений. Подгонять разбиение под результат запрещено, и отдельный
файл существует ровно затем, чтобы дата его появления была видна в истории.

Различающий вопрос к каждому коду: **существует ли эта проверка из-за сигнала,
относящегося к ЭТОЙ площадке?** Да — по поводу. Нет, проверка идёт по
расписанию или программе — плановая.
"""

from __future__ import annotations

BY_SIGNAL = {
    # Следует за прежней находкой на этой же площадке.
    "FUI": "проверка вслед за предыдущей: существует из-за её результата",
    # Проводится ради подготовки дела о принуждении.
    "CDI": "проверка ради развития дела: назначается, когда нарушение уже подозревают",
    # Проверяет исполнение графика, назначенного после нарушения.
    "CSE": "оценка графика приведения в соответствие: графика без нарушения не бывает",
    # Проверяет исполнение предписанных корректирующих действий.
    "CAC": "оценка корректирующих действий: они предписываются после находки",
    # Запись о признании площадки значимым нарушителем и о снятии этого статуса.
    "SNY": "признание значимым нарушителем: запись о статусе, а не плановый обход",
    "SNN": "снятие статуса значимого нарушителя: следует за его присвоением",
    # Площадка сама сообщила о проблеме.
    "FSD": "самораскрытие площадки: сигнал исходит от самого объекта надзора",
    # Следует за запросом сведений по разделу 3007.
    "NIR": "отсутствие ответа на запрос сведений: следует за самим запросом",
}

SCHEDULED = {
    "CEI": "плановая проверка соответствия: основной обход по программе",
    "FCI": "плановая проверка по части операций",
    "NRR": "плановая проверка нефинансовых записей",
    "FRR": "плановая проверка финансового обеспечения",
    "CAV": "визит помощи: не предполагает подозрения",
    "GME": "плановая оценка мониторинга подземных вод",
    "OAM": "плановая проверка эксплуатации и обслуживания",
}

TRIGGERED = "по поводу"
ROUTINE = "плановая"
UNKNOWN = "не разобран"


def trigger_class(code: str | None) -> str:
    """К какому роду отнесён повод. Неизвестный код называется, а не молчит."""
    if code in BY_SIGNAL:
        return TRIGGERED
    if code in SCHEDULED:
        return ROUTINE
    return UNKNOWN
