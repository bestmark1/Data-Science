"""Описание задачи и предпосылки, при которых проверки осмысленны.

Половина требований, выведенных на одном кейсе, несла скрытые предпосылки:
событийный процесс со статусами, отложенный исход, бинарный вероятностный
таргет, регулярный поток сбора. Поданы они были как универсальные.

Здесь предпосылки становятся машинными. Проверка объявляет, при каких условиях
она осмысленна, и выключается вместе с ними — а не срабатывает вхолостую на
задаче другого типа.

Реализация пока одна: бинарный таргет с отложенным исходом. Интерфейс обязан
допускать остальные, иначе второй кейс в другой отрасли упрётся в него.
"""

from __future__ import annotations

from enum import StrEnum

from pydantic import BaseModel, ConfigDict


class TargetKind(StrEnum):
    """Тип целевой величины."""

    BINARY = "binary"
    REGRESSION = "regression"
    COMPETING = "competing"
    """Несколько взаимоисключающих исходов: наступает не более одного.

    Отличается от многоклассовой задачи тем, что наступление одного исхода
    ОБРЫВАЕТ наблюдение за остальными. Отказ одного компонента не является
    отрицательным исходом для другого: машину остановили и починили, и что
    случилось бы со вторым компонентом, неизвестно.
    """

    RANKING = "ranking"
    SURVIVAL = "survival"
    UPLIFT = "uplift"


class OutcomeTiming(StrEnum):
    """Когда исход становится известен относительно момента решения."""

    IMMEDIATE = "immediate"
    """Известен сразу. Зазор в сплите и зрелость метки неприменимы."""

    DELAYED = "delayed"
    """Созревает позже. Момент узнавания выводится из определения исхода."""


class ObjectLifetime(StrEnum):
    """Сколько решений приходится на один объект реального мира."""

    ONE_SHOT = "one_shot"
    """Объект существует ради одного решения. Заказ, заявка, транзакция.

    Присутствие такого объекта по обе стороны сплита — утечка.
    """

    RECURRING = "recurring"
    """Объект живёт долго и получает много решений. Машина, клиент, пациент.

    Присутствие по обе стороны сплита неизбежно и утечкой само по себе не
    является: утечка возникает при пересечении интервалов наблюдения, из
    которых построены признаки.
    """


class Simultaneity(StrEnum):
    """Что делать, когда несколько видов события наступают разом.

    Конкурирующие риски предполагают, что побеждает ровно один. На втором
    кейсе допущение оказалось нарушено: 42 момента отказа из 719 затрагивали
    два компонента одновременно.

    По таблице решений это не проверить — там один вид на строку, а нарушение
    происходит раньше, при её сборке. Поэтому ответ объявляется.
    """

    NOT_POSSIBLE = "not_possible"
    """Одновременность исключена устройством процесса. Требует основания:
    на втором кейсе такое объявление было бы ложным."""

    OWN_KIND = "own_kind"
    """Одновременный случай — отдельный вид исхода. Для остальных видов такие
    строки цензурируются сами, и знание не выдумывается."""

    EXCLUDED = "excluded"
    """Такие строки выводятся из популяции. Смещает выборку, и это видно."""


class Premise(StrEnum):
    """Предпосылка, при которой требование осмысленно.

    Соответствует пометкам области действия в наблюдённой спецификации.
    """

    UNIVERSAL = "universal"
    PROCESS = "process"
    """Есть событийный процесс со статусами и упорядоченными метками."""

    DELAYED_OUTCOME = "delayed_outcome"
    BINARY_TARGET = "binary_target"
    STREAM = "stream"
    """Данные собираются регулярным временным потоком."""


class TaskSpec(BaseModel):
    """Что за задача решается и какие предпосылки выполнены."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    target_kind: TargetKind
    outcome_timing: OutcomeTiming

    has_process: bool = False
    """Есть ли событийный процесс со статусами."""

    object_lifetime: ObjectLifetime | None = None
    """Живёт ли объект дольше одного решения.

    Второй кейс показал, что две проверки опирались на невысказанное допущение
    об одноразовости объекта. Заказ случается один раз; машина обслуживается
    годами. По данным эти случаи неотличимы — различает их только устройство
    предметной области.

    None означает, что ответа нет. Тогда работа блокируется: блокировать надо
    отсутствие ответа, а не саму ситуацию.
    """

    is_stream: bool = False
    """Собираются ли данные регулярным временным потоком."""

    simultaneous_kinds: Simultaneity | None = None
    """Что делать с одновременным наступлением нескольких видов события.

    Обязательно при конкурирующих исходах. При склейке в бинарный исход не
    имеет значения: отказало что-нибудь — метка единица независимо от числа
    отказавших.
    """

    kinds_collapsed: bool | None = None
    """Намеренно ли несколько видов событий сведены в один исход.

    None означает, что ответа нет. Свести четыре вида отказа в исход «отказало
    хоть что-то» бывает верно: если вмешательство одно на все виды, различать
    их незачем. Бывает и ошибкой: если ремонт адресный, модель предсказывает
    не то, чем управляют.

    Из данных это не выводится — как и жизненный цикл объекта. Поэтому
    блокируется отсутствие ответа, а не сама склейка.
    """

    def satisfies(self, premise: Premise) -> bool:
        """Выполнена ли предпосылка."""
        match premise:
            case Premise.UNIVERSAL:
                return True
            case Premise.PROCESS:
                return self.has_process
            case Premise.DELAYED_OUTCOME:
                return self.outcome_timing is OutcomeTiming.DELAYED
            case Premise.BINARY_TARGET:
                return self.target_kind is TargetKind.BINARY
            case Premise.STREAM:
                return self.is_stream

    def satisfies_all(self, premises: frozenset[Premise]) -> bool:
        return all(self.satisfies(p) for p in premises)

    def unmet(self, premises: frozenset[Premise]) -> frozenset[Premise]:
        """Предпосылки, которые не выполнены. Пусто — проверка применима."""
        return frozenset(p for p in premises if not self.satisfies(p))


SUPPORTED = frozenset(
    {
        (TargetKind.BINARY, OutcomeTiming.DELAYED),
        (TargetKind.COMPETING, OutcomeTiming.DELAYED),
    }
)
"""Комбинации, для которых есть реализация. Интерфейс шире реализации намеренно."""


class UnsupportedTask(Exception):
    """Тип задачи описан корректно, но реализации для него пока нет."""


def require_supported(task: TaskSpec) -> None:
    """Отказать явно, а не выдать неверный результат молча."""
    if (task.target_kind, task.outcome_timing) not in SUPPORTED:
        raise UnsupportedTask(
            f"задача {task.target_kind.value} / {task.outcome_timing.value} описана "
            "корректно, но реализации для неё нет. Поддерживается: "
            + ", ".join(f"{k.value}/{t.value}" for k, t in sorted(SUPPORTED))
        )
