"""Область смысла каждого порога: где значение вообще может лежать.

Область — НЕ утверждение о том, что число верное. Она говорит слабее и потому
честнее: вот пределы, за которыми значение перестаёт быть порогом. Доля больше
единицы не бывает. Кратность, не превышающая единицы, означает «любое отличие»
и превращает проверку во всегда-включённую. Сила связи по построению не
превосходит 0.5, и порог выше этого выключает проверку целиком.

Зачем это записано отдельно. Замер прибитости порогов объявил долю в 22%, и
доля была завышена: часть мутантов уводила значение ЗА область смысла, где
проверка становится всегда-включённой или всегда-выключенной. Такое убийство
уже посчитано мутантом выключения и о границе не говорит ничего. Мутировать
следует внутри области, а для этого область надо объявить.

Побочная польза оказалась больше основной. Чтобы назвать пределы, приходится
вслух сказать, что порог означает, — и `N6.floor = 0.35` при потолке силы 0.5
выглядит иначе, чем выглядел: он отсекает не «слабые связи», а всё, кроме
верхней трети возможного диапазона.

Ключ — `требование.поле` для полей классов и `модуль.ИМЯ` для констант.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class Domain:
    """Пределы, внутри которых значение остаётся порогом.

    Границы СТРОГИЕ с обеих сторон: `low < value < high`. Так и должно быть.
    Доля, равная нулю, означает «срабатывать всегда», равная единице —
    «не срабатывать никогда»; ни то ни другое порогом не является.
    """

    low: float
    high: float | None
    """None — верхней границы нет."""

    reason: str
    """Откуда взяты пределы. Из устройства величины, а не из вкуса автора."""

    def admits(self, value: float) -> bool:
        return self.low < value and (self.high is None or value < self.high)


